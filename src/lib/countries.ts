/** Barème IUTS Burkina Faso (mensuel) — utilisé comme référence SYSCOHADA. */
export const IUTS_BRACKETS = [
  { from: 0, to: 25000, rate: 0 },
  { from: 25000, to: 50000, rate: 0.0825 },
  { from: 50000, to: 75000, rate: 0.1375 },
  { from: 75000, to: 125000, rate: 0.165 },
  { from: 125000, to: 250000, rate: 0.22 },
  { from: 250000, to: Infinity, rate: 0.275 },
];

export function computeIuts(base: number): number {
  let tax = 0;
  for (const b of IUTS_BRACKETS) {
    if (base <= b.from) break;
    const slice = Math.min(base, b.to) - b.from;
    if (slice > 0) tax += slice * b.rate;
  }
  return Math.round(tax);
}
